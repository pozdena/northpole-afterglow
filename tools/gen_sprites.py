#!/usr/bin/env python3
"""Turn art/sprites.txt into src/sprites_gen.h (and, with --sheet, a PNG contact sheet).

The palette lives HERE and is emitted into the header, so the art, the C code and the
preview always agree on colors.

Pixel encoding in the generated table:
    0           transparent
    1..N        palette index + 1
    100 + k     per-instance color slot k (art chars '1'..'4' -> k = 0..3)
    200         twinkling light ('*')
    201         lit window ('!')
    202         settled snow ('s': white once a snowfall has built it up, else nothing)
    210 + i     settled snow over palette color i: that color until snow covers it
                (a sprite headed "@name bare=G" has its 's' pixels over G)
    ('~' is settled snow over nothing, whatever the sprite's bare color)
"""
import argparse
import pathlib
import sys

# char, C name, RGB (Atari-ish NTSC values, a little brighter for a modern panel)
PALETTE = [
    ("K", "BLACK",     (0x00, 0x00, 0x00)),
    ("W", "WHITE",     (0xEC, 0xEC, 0xEC)),
    ("w", "SNOWSHADE", (0x9C, 0xA4, 0xB4)),
    ("D", "DKGRAY",    (0x58, 0x58, 0x5C)),
    ("R", "RED",       (0xD8, 0x38, 0x34)),
    ("r", "DKRED",     (0x88, 0x20, 0x1C)),
    ("G", "GREEN",     (0x40, 0xAC, 0x40)),
    ("g", "DKGREEN",   (0x1C, 0x70, 0x2C)),
    ("B", "BROWN",     (0x98, 0x60, 0x30)),
    ("b", "DKBROWN",   (0x5C, 0x34, 0x14)),
    ("Y", "YELLOW",    (0xFC, 0xE0, 0x5C)),
    ("O", "ORANGE",    (0xF0, 0x8C, 0x24)),
    ("S", "SKIN",      (0xF4, 0xBC, 0x94)),
    ("L", "LTBLUE",    (0xA4, 0xCC, 0xFC)),
    ("U", "BLUE",      (0x40, 0x60, 0xE0)),
    ("P", "PINK",      (0xF4, 0x90, 0xB4)),
    ("T", "TAN",       (0xD0, 0xA8, 0x6C)),
    ("M", "MAGENTA",   (0xD0, 0x44, 0xC8)),
    ("C", "CYAN",      (0x54, 0xD4, 0xD4)),
    ("N", "GOLD",      (0xD4, 0xA4, 0x1C)),
    (None, "DIMWHITE", (0x70, 0x74, 0x80)),   # faint stars, settled snow far away
    # the sky behind clouds: with the grays above, a ramp from white down to black
    (None, "FADE7",    (0xC8, 0xCA, 0xD0)),
    (None, "FADE5",    (0x84, 0x88, 0x94)),
    (None, "FADE2",    (0x3C, 0x3E, 0x44)),
    (None, "FADE1",    (0x20, 0x21, 0x24)),
    # more skin tones, for the maids and ladies; kept light enough to read on black
    (None, "SKIN2",    (0xD8, 0x9C, 0x6C)),
    (None, "SKIN3",    (0xB4, 0x78, 0x4C)),
]
CHAR_INDEX = {c: i for i, (c, _, _) in enumerate(PALETTE) if c}
SLOT_BASE, TWINKLE, WINDOW, SETTLED, SETTLED_ON = 100, 200, 201, 202, 210
assert SETTLED_ON + len(PALETTE) <= 256
BARE = {}   # sprite name -> the color its settled snow covers


def parse(path):
    sprites, name, rows = [], None, []

    def flush():
        if name is not None:
            if not rows:
                sys.exit(f"sprite {name} has no rows")
            sprites.append((name, rows))

    for lineno, raw in enumerate(path.read_text().splitlines(), 1):
        line = raw.rstrip()
        if line.startswith("#"):
            continue
        if line.startswith("@"):
            flush()
            words = line[1:].split()
            name, rows = words[0], []
            for opt in words[1:]:
                key, _, val = opt.partition("=")
                if key != "bare" or val not in CHAR_INDEX:
                    sys.exit(f"{path}:{lineno}: bad option '{opt}'")
                BARE[name] = val
        elif line == "":
            flush()
            name, rows = None, []
        elif name is None:
            sys.exit(f"{path}:{lineno}: pixels outside a sprite")
        else:
            rows.append(line)
    flush()
    return sprites


def encode(ch, where, bare=None):
    if ch == ".":
        return 0
    if ch in "1234":
        return SLOT_BASE + int(ch) - 1
    if ch == "*":
        return TWINKLE
    if ch == "!":
        return WINDOW
    if ch == "s":
        return SETTLED_ON + CHAR_INDEX[bare] if bare else SETTLED
    if ch == "~":
        return SETTLED
    if ch in CHAR_INDEX:
        return CHAR_INDEX[ch] + 1
    sys.exit(f"{where}: unknown pixel '{ch}'")


def build(sprites):
    out, table = [], []
    for name, rows in sprites:
        w, h = max(len(r) for r in rows), len(rows)
        if w > 255 or h > 255:
            sys.exit(f"sprite {name} too big")
        table.append((name, w, h, len(out)))
        for y, r in enumerate(rows):
            for x in range(w):
                out.append(encode(r[x] if x < len(r) else ".", f"{name} row {y}",
                                  BARE.get(name)))
    return out, table


def write_header(path, data, table):
    L = ["/* GENERATED by tools/gen_sprites.py from art/sprites.txt. Do not edit. */",
         "#ifndef SPRITES_GEN_H", "#define SPRITES_GEN_H", ""]
    for i, (_, cname, _) in enumerate(PALETTE):
        L.append(f"#define C_{cname} {i}")
    L.append(f"#define NUM_COLORS {len(PALETTE)}")
    L.append(f"#define PX_SLOT {SLOT_BASE}\n#define PX_TWINKLE {TWINKLE}\n#define PX_WINDOW {WINDOW}\n"
             f"#define PX_SETTLED {SETTLED}\n#define PX_SETTLED_ON {SETTLED_ON}\n")
    L.append("static const unsigned char PAL_RGB[NUM_COLORS][3] = {")
    L += [f"    {{0x{r:02X}, 0x{g:02X}, 0x{b:02X}}}, /* {n} */" for _, n, (r, g, b) in PALETTE]
    L.append("};\n")
    for i, (name, *_rest) in enumerate(table):
        L.append(f"#define SPR_{name.upper()} {i}")
    L.append(f"#define NUM_SPRITES {len(table)}\n")
    L.append("/* width, height, offset into SPR_PX (offset as two bytes, high first) */")
    L.append("static const unsigned char SPR_DIM[NUM_SPRITES][4] = {")
    L += [f"    {{{w}, {h}, {off >> 8}, {off & 0xFF}}}, /* {n} */" for n, w, h, off in table]
    L.append("};\n")
    L.append(f"static const unsigned char SPR_PX[{len(data)}] = {{")
    for i in range(0, len(data), 24):
        L.append("    " + ",".join(str(v) for v in data[i:i + 24]) + ",")
    L.append("};\n\n#endif")
    path.write_text("\n".join(L) + "\n")


def write_sheet(path, sprites, scale=6):
    from PIL import Image, ImageDraw
    slot_demo = [(0x40, 0xAC, 0x40), (0xD8, 0x38, 0x34), (0xD8, 0x38, 0x34), (0x40, 0x60, 0xE0)]
    pad = 4
    widths = [max(len(r) for r in rows) for _, rows in sprites]
    heights = [len(rows) for _, rows in sprites]
    W = sum(w + pad for w in widths) + pad
    img = Image.new("RGB", (min(W, 260) * scale, 1), (0, 0, 0))
    # flow layout
    rows_out, cur, cx, rh = [], [], pad, 0
    for (name, rows), w, h in zip(sprites, widths, heights):
        if cx + w + pad > 260 and cur:
            rows_out.append((cur, rh)); cur, cx, rh = [], pad, 0
        cur.append((name, rows, cx)); cx += w + pad; rh = max(rh, h)
    rows_out.append((cur, rh))
    H = sum(rh + pad + 3 for _, rh in rows_out) + pad
    img = Image.new("RGB", (260 * scale, H * scale), (0, 0, 0))
    d = ImageDraw.Draw(img)
    y0 = pad
    for cur, rh in rows_out:
        for name, rows, x0 in cur:
            for y, r in enumerate(rows):
                for x, ch in enumerate(r):
                    if ch == ".":
                        continue
                    if ch in CHAR_INDEX:
                        col = PALETTE[CHAR_INDEX[ch]][2]
                    elif ch in "1234":
                        col = slot_demo[int(ch) - 1]
                    elif ch in "s~":
                        col = PALETTE[CHAR_INDEX["W"]][2]
                    elif ch == "*":
                        col = [(0xD8, 0x38, 0x34), (0xFC, 0xE0, 0x5C), (0x40, 0x60, 0xE0), (0x54, 0xD4, 0xD4)][(x + y) % 4]
                    else:
                        col = (0xFC, 0xE0, 0x5C)
                    X, Y = (x0 + x) * scale, (y0 + y) * scale
                    d.rectangle([X, Y, X + scale - 1, Y + scale - 1], fill=col)
            d.text((x0 * scale, (y0 + len(rows) + 0.5) * scale), name, fill=(120, 120, 120))
        y0 += rh + pad + 3
    img.save(path)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("art", type=pathlib.Path)
    ap.add_argument("header", type=pathlib.Path)
    ap.add_argument("--sheet", type=pathlib.Path)
    a = ap.parse_args()
    sprites = parse(a.art)
    data, table = build(sprites)
    if len(data) > 65535:
        sys.exit("sprite data too large")
    write_header(a.header, data, table)
    if a.sheet:
        write_sheet(a.sheet, sprites)
    print(f"{len(table)} sprites, {len(data)} bytes")


if __name__ == "__main__":
    main()
